DROP TABLE IF EXISTS event_teams RESTRICT;

-- Teams registered to compete in an event; a match can only use registered teams
CREATE TABLE event_teams(
	event_team_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	event_id INTEGER NOT NULL,
	team_id INTEGER NOT NULL,
	registered_on TIMESTAMPTZ NOT NULL DEFAULT NOW(),

	CONSTRAINT fk_events
	FOREIGN KEY (event_id)
	REFERENCES events(event_id)
	ON DELETE CASCADE,

	CONSTRAINT fk_teams
	FOREIGN KEY (team_id)
	REFERENCES teams(team_id),

	CONSTRAINT uq_event_team
	UNIQUE(event_id, team_id)
);
