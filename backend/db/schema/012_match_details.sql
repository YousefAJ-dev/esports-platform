DROP TABLE IF EXISTS match_details RESTRICT;

-- One row per team per match (session), holding that team's result
CREATE TABLE match_details(
	match_detail_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	session_id INTEGER NOT NULL,
	team_id INTEGER NOT NULL,
	score INTEGER,
	is_winner BOOLEAN NOT NULL DEFAULT FALSE,
	created_on TIMESTAMPTZ NOT NULL DEFAULT NOW(),

	-- A result can only exist for a team that is actually in the match
	CONSTRAINT fk_session_team
	FOREIGN KEY (session_id, team_id)
	REFERENCES session_teams(session_id, team_id)
	ON DELETE CASCADE,

	CONSTRAINT uq_match_detail
	UNIQUE(session_id, team_id),

	CONSTRAINT chk_match_score CHECK (score >= 0)
);

-- At most one winner per match
CREATE UNIQUE INDEX uq_match_winner
	ON match_details(session_id)
	WHERE is_winner;
